do $english$
declare f record; r record; definition text; translated text;
begin
 for f in select p.oid from pg_proc p join pg_namespace n on n.oid=p.pronamespace where n.nspname='public' and p.prokind='f' and pg_get_functiondef(p.oid) ~ '[А-Яа-яЁё]' loop
  definition:=pg_get_functiondef(f.oid); translated:=definition;
  for r in select * from english_translation loop
   translated:=replace(translated,quote_literal(r.source),quote_literal(r.target));
  end loop;
  if translated<>definition then execute translated; end if;
 end loop;
end $english$;
create function pg_temp.english_text(value text) returns text language sql as $$
 select case when value like 'Файл: %' then 'File: '||substr(value,7) else coalesce((select target from english_translation where source=value),value) end;
$$;
create function pg_temp.english_json(value jsonb) returns jsonb language plpgsql as $$
declare result jsonb;
begin
 case jsonb_typeof(value)
 when 'string' then return to_jsonb(pg_temp.english_text(value #>> '{}'));
 when 'object' then select jsonb_object_agg(key,pg_temp.english_json(v)) into result from jsonb_each(value) as t(key,v); return coalesce(result,'{}');
 when 'array' then select jsonb_agg(pg_temp.english_json(v) order by ord) into result from jsonb_array_elements(value) with ordinality as t(v,ord); return coalesce(result,'[]');
 else return value;
 end case;
end $$;
