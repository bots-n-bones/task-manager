import assert from 'node:assert/strict';
import {webcrypto} from 'node:crypto';
import {newRequestId,watchTheme,requestJson} from '../../web/browser.mjs';
const uuid=/^[a-f0-9]{8}-[a-f0-9]{4}-4[a-f0-9]{3}-[89ab][a-f0-9]{3}-[a-f0-9]{12}$/;
const fallback={getRandomValues:bytes=>webcrypto.getRandomValues(bytes)};
const ids=Array.from({length:100},()=>newRequestId(fallback));
assert.ok(ids.every(id=>uuid.test(id)));assert.equal(new Set(ids).size,100);
const modern=webcrypto.randomUUID();assert.equal(newRequestId({randomUUID:()=>modern}),modern);
assert.throws(()=>newRequestId({}),/secure requests/);
let subscribed,callback=()=>{};
watchTheme({addEventListener:(event,fn)=>subscribed={event,fn}},callback);
assert.deepEqual(subscribed,{event:'change',fn:callback});
watchTheme({addListener:fn=>subscribed=fn},callback);assert.equal(subscribed,callback);
assert.doesNotThrow(()=>watchTheme({matches:false},callback));
const success=await requestJson('/api/test',{},async()=>new Response('{"ok":true}',{status:200}));
assert.equal(success.result.ok,true);
await assert.rejects(requestJson('/api/test',{},async()=>{throw TypeError('Failed to fetch');}),/Check your connection/);
await assert.rejects(requestJson('/api/test',{},async()=>new Response('<html>Bad gateway</html>',{status:502})),error=>error.status===502&&/temporarily unavailable/.test(error.message));
const expired=await requestJson('/api/test',{},async()=>new Response('{"error":"Sign-in required"}',{status:401}));
assert.equal(expired.response.status,401);
console.log('Secure request ID fallback, theme listeners, JSON responses and network failures verified');
